# -*- coding: utf-8 -*-
"""
演習：検査サービスの請求額を基本演算で計算する（解説付き解答版）

【想定する場面】
検査会社が、複数の検体をまとめて依頼してきた顧客へ請求書を発行する。
単価×検体数から小計を出し、まとめ依頼の値引きを引いたあとに消費税を
加えて、最終的な請求額を求める。

（課題）
1. 単価と検体数から小計を計算する。
2. 小計から値引き額を引き、値引後の金額を求める。
3. 値引後の金額に消費税をかけ、税額を求める。
4. 値引後の金額と税額を足して、最終的な請求額を求める。
"""

unit_price = 4800       # 1検体あたりの検査料金（円）
samples = 25            # 検体数
discount = 12000        # 一括依頼の値引き額（円）
tax_rate = 0.10         # 消費税率（10%）

# 単価 × 検体数で、値引き・税抜き前の合計金額（小計）を求めます。
subtotal = unit_price * samples

# 小計から値引き額を引きます。消費税は「値引後の金額」に対して
# かけるのが一般的なので、先に値引きを済ませておきます。
after_discount = subtotal - discount

# 値引後の金額に税率をかけて、消費税額を求めます。
tax = after_discount * tax_rate

# 値引後の金額と消費税を足したものが、最終的な請求額になります。
total = after_discount + tax

# f"{値:,}" のように桁区切り(,)を指定すると、3桁ごとにカンマが入り、
# 金額として読みやすい表示になります。
# ":.0f" を付けると、小数点以下を四捨五入して整数で表示します。
print(f"小計: {subtotal:,}円")
print(f"値引後: {after_discount:,}円")
print(f"消費税: {tax:,.0f}円")
print(f"請求額: {total:,.0f}円")

# 【ポイント】
# ・「値引き→消費税」の順番が逆になると（税込金額から値引く）、結果が変わります。
#   実務では、どちらの順番で計算するのが正しいか契約や税法のルールを確認します。
