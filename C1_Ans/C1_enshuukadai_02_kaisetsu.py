# -*- coding: utf-8 -*-
"""
演習：倉庫内の直線距離と保管容量を計算する（解説付き解答版）

【想定する場面】
倉庫内の2つの作業地点が、水平方向と垂直方向にそれぞれ離れた位置にある。
移動距離の目安として、2点間の直線距離を求めたい。
また、棚の段数と1段あたりの収納数から、棚全体の最大保管数も求めたい。

（課題）
1. 水平方向・垂直方向の距離から、三平方の定理を使って直線距離を求める。
2. 棚の段数と1段あたりの箱数から、棚全体の最大保管数を求める。
"""

import math

horizontal_m = 9   # 水平方向の距離（メートル）
vertical_m = 12    # 垂直方向の距離（メートル）

# 三平方の定理（ピタゴラスの定理）を使います。
# 直角三角形において、直線距離（斜辺）の2乗は、水平距離と垂直距離それぞれの
# 2乗を足したものに等しくなります： 直線距離 = √(水平² + 垂直²)
# math.sqrt() は平方根（ルート）を計算する関数です。
straight_distance = math.sqrt(horizontal_m ** 2 + vertical_m ** 2)

shelf_levels = 5        # 棚の段数
boxes_per_level = 24    # 1段あたりに収納できる箱数

# 段数 × 1段あたりの箱数で、棚全体に収納できる箱の最大数を求めます。
capacity = shelf_levels * boxes_per_level

print(f"作業地点間の直線距離: {straight_distance:.1f}m")
print(f"棚の最大保管数: {capacity}箱")

# 【ポイント】
# ・「水平方向」「垂直方向」のように直角に交わる2つの移動を1本の直線で
#   近似したいとき、三平方の定理がよく使われます。
# ・**（べき乗）演算子は、math.sqrtやmath.powと組み合わせてよく使われます。
