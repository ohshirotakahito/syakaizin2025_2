# -*- coding: utf-8 -*-
"""
演習：10店舗の販売数をNumPy配列で扱う（解説付き解答版）

【想定する場面】
10店舗を展開するチェーン店で、各店舗の本日の販売数が集計された。
店舗番号と販売数を対応させて管理し、全店合計と平均を求めたい。

（課題）
1. 店舗番号（1～10）をNumPy配列として作る。
2. 各店舗の販売数をNumPy配列として作る。
3. 全店の合計販売数と、平均販売数を求めて表示する。
"""

import numpy as np

# NumPyは、たくさんの数値をまとめて高速に計算するためのライブラリです。
# 普通のPythonのリストより、合計や平均などの計算を簡単に書けます。

# np.arange(1, 11)は「1以上11未満」の整数を1つずつ並べた配列を作ります。
# つまり 1, 2, 3, ... , 10 の10個の数字が入ります（11は含まれません）。
store_numbers = np.arange(1, 11)

# np.array()は、Pythonのリストをそのまま配列（NumPy配列）に変換します。
# ここでは10店舗ぶんの「本日の販売数」を1つの配列にまとめています。
daily_sales = np.array([82, 95, 71, 104, 88, 120, 67, 99, 110, 91])

print("店舗番号:", store_numbers)
print("販売数:", daily_sales)

# .sum()は配列に入っているすべての数値を足し合わせます。
# .mean()は配列の平均値（合計 ÷ 個数）を計算します。
# f"{...:.1f}"は、小数点以下1桁までの見やすい形で数値を文字列に埋め込む書き方です。
print(f"全店合計={daily_sales.sum()}個、平均={daily_sales.mean():.1f}個")

# 【ポイント】
# ・NumPy配列は「同じ種類のデータ（今回は整数）をまとめて扱う箱」というイメージです。
# ・sum()やmean()のように、配列全体に対する計算を1回の命令でできるのがNumPyの強みです。
