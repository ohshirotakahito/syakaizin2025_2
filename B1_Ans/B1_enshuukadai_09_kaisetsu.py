# -*- coding: utf-8 -*-
"""
演習：売上表へ客単価を追加し、一時列を削除する（解説付き解答版）

【想定する場面】
店舗ごとの売上金額と来店客数のデータから、「客単価」（お客様1人あたりの
平均購入金額）を計算したい。社内分析では来店客数の列も残しておきたいが、
外部への報告資料では客単価だけを見せたいので、報告用には来店客数の列を
取り除いた表を作る。

（課題）
1. 店舗名、売上金額、来店客数を持つ表（DataFrame）を作る。
2. 売上金額 ÷ 来店客数で「客単価」の列を追加する。
3. 外部報告用に、来店客数の列を取り除いた表を作る。
"""

import pandas as pd

sales = pd.DataFrame({
    "store": ["Tokyo", "Osaka", "Fukuoka"],
    "sales_yen": [520000, 430000, 310000],
    "customers": [410, 370, 260],
})

# 既存の列同士を計算し、その結果を新しい列名で代入すると、
# DataFrameへ新しい列を追加できます。
# ここでは「売上金額 ÷ 来店客数」で、1人あたりの平均購入金額を求めています。
sales["sales_per_customer"] = sales["sales_yen"] / sales["customers"]

# .round(1) は、表示のために小数点以下1桁に丸めています（元のデータは変わりません）。
print(sales.round(1))

# drop(columns="customers") は、指定した列を取り除いた「新しい表」を作ります。
# 元のsales自体からは列は削除されず、そのまま残ります。
report = sales.drop(columns="customers")

print("\n【外部報告用】")
print(report.round(1))

# 【ポイント】
# ・列同士の四則演算（+, -, *, /）は、行ごとに自動的に計算されます。
# ・drop(columns=...)は元の表を変えず、「列を除いた別の表」を新しく作る点に注意しましょう。
#   （元の表自体から列を消したい場合は、drop(columns=..., inplace=True)を使います。）
