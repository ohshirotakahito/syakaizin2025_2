# -*- coding: utf-8 -*-
"""
演習：配送時間の代表値を集計する（解説付き解答版）

【想定する場面】
配送にかかった時間（分）の記録がある。この中には、渋滞などで
大きく時間がかかった特別なケース（80分）も含まれている。
平均だけを見ると、そうした極端な値に引っ張られて実態と
ずれてしまうことがあるため、平均と中央値の両方を確認したい。

（課題）
1. 配送時間の記録を持つ表（DataFrame）を作る。
2. 平均・中央値・最大値をそれぞれ求めて表示する。
3. 極端な値（外れ値）が結果に与える影響について考える。
"""

import pandas as pd

deliveries = pd.DataFrame({"minutes": [28, 35, 31, 44, 29, 80, 33, 37]})

# .mean() は列全体の平均値（合計 ÷ 個数）を計算します。
# 80分のような極端に大きい値があると、平均は実際の「典型的な配送時間」より
# 大きめに引っ張られてしまいます。
print(f"平均={deliveries['minutes'].mean():.1f}分")

# .median() は「値を小さい順に並べたときの真ん中の値（中央値）」です。
# 極端な値（外れ値）の影響を受けにくいという特徴があります。
print(f"中央値={deliveries['minutes'].median():.1f}分")

# .max() は列の中で最も大きい値です。
print(f"最大={deliveries['minutes'].max()}分")

print("80分の遅延があるため、平均と中央値の両方を確認します。")

# 【ポイント】
# ・平均は外れ値（極端に大きい・小さい値）の影響を受けやすい代表値です。
# ・中央値は外れ値の影響を受けにくいため、平均と合わせて確認すると
#   データの実態をより正確につかめます。
