# -*- coding: utf-8 -*-
"""
演習：欠測した温度センサー値を補完する（解説付き解答版）

【想定する場面】
温度センサーの記録の一部が、通信不良などの理由で欠測（記録なし）に
なってしまった。欠測値をそのままにしておくと、その後の平均計算や
グラフ作成でエラーになったり、結果が不正確になったりすることがある。
そこで、欠測値を「もっともらしい値」で埋める（補完する）処理を行う。

（課題）
1. 温度の記録（一部欠測あり）を持つ表（DataFrame）を作る。
2. 欠測している値の数を確認する。
3. 欠測値を、記録全体の中央値で埋める。
"""

import numpy as np
import pandas as pd

# np.nan は「値がない（欠測）」ことを表す特別な値です。
# pandasやNumPyでは、欠測値をこのnp.nanで表すのが一般的です。
sensor = pd.DataFrame({"temperature_c": [4.1, 4.3, np.nan, 4.0, 4.4]})

# .isna() は、各値が欠測（NaN）かどうかをTrue/Falseで返します。
# .sum() を続けると、True（欠測）の個数を数えられます（True=1として合計するため）。
# .iloc[0] で、結果（1列分のSeries）から最初の値だけを取り出しています。
print("欠損数:", sensor.isna().sum().iloc[0])

# 欠測値を0で埋めると、温度としてはあり得ない異常な値になってしまいます。
# そこで、正常に記録されているデータの「中央値」で埋めることにします。
# 中央値は平均と違い、極端な値の影響を受けにくいという特徴があります。
median_temperature = sensor["temperature_c"].median()

# .fillna(値) は、欠測している部分だけをその値で置き換えます。
# 欠測していない値はそのまま変わりません。
sensor["temperature_c"] = sensor["temperature_c"].fillna(median_temperature)

print(sensor)

# 【ポイント】
# ・欠測値を0や適当な値で埋めると、分析結果が歪む原因になります。
# ・「中央値で埋める」「平均で埋める」「前後の値で埋める」など、
#   データの性質に合わせて補完方法を選ぶことが大切です。
